/**
 * Extensible Plan Registry Helper
 * Allows future custom plans to be added dynamically at runtime without rewriting the application.
 */
export function registerCustomPlan(customPlan: SubscriptionPlan): SubscriptionPlan[] {
  const existingIdx = subscriptionPlans.findIndex(
    (p) => p.plan_id === customPlan.plan_id || p.id === customPlan.id
  );
  if (existingIdx >= 0) {
    subscriptionPlans[existingIdx] = { ...subscriptionPlans[existingIdx], ...customPlan };
  } else {
    subscriptionPlans.push(customPlan);
  }
  return subscriptionPlans;
}

export function getSubscriptionPlan(planId: string): SubscriptionPlan | undefined {
  return subscriptionPlans.find((p) => p.plan_id === planId || p.id === planId);
}

export function getActiveSubscriptionPlans(): SubscriptionPlan[] {
  return subscriptionPlans.filter((p) => p.status === 'active');
}

