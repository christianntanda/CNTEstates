export function formatCurrency(amount: number, currency: Currency = 'USD', lang: Language = 'en', decimals?: number): string {
  return formatCurrencyAmount(amount, currency, lang, { decimals });
}

export function formatDate(dateString: string, lang: Language = 'en'): string {
  const localeMap: Record<Language, string> = {
    en: 'en-US',
    fr: 'fr-FR',
    es: 'es-ES',
    pt: 'pt-BR',
  };
  try {
    const d = new Date(dateString);
    return new Intl.DateTimeFormat(localeMap[lang] || 'en-US', {
      year: 'numeric',
      month: 'short',
      day: 'numeric',
    }).format(d);
  } catch {
    return dateString;
  }
}
